function P = presets()
%PRESETS Benign and melanoma phenotype presets with per-parameter provenance.
%
%   P = PRESETS() returns a struct with:
%       P.benign     - parameter values for a benign (nevus-like) phenotype
%       P.melanoma   - parameter values for a malignant phenotype
%       P.provenance - struct: parameter name -> citation or 'TBD' string
%
%   Document section 6 requires every parameter to be literature-grounded or
%   explicitly marked TBD. The hybrid-CA *framework* follows Anderson (2005);
%   the specific numeric values below are deliberate order-of-magnitude
%   choices to be confirmed against the literature in the sweep, and each is
%   tagged accordingly rather than given a fabricated citation.
%
%   The benign/malignant contrast is the mechanistic hypothesis under test,
%   not an assertion: benign retains contact inhibition (beta high) and
%   adhesion (A_i high) with low migration; malignant loses both.

P = struct();

P.benign = struct( ...
    'alpha',   0.20, ...
    'beta',    0.95, ...
    'P_move',  0.02, ...
    'A_i',     0.90, ...
    'T_cell',  4, ...
    'delta',   1e-4);

P.melanoma = struct( ...
    'alpha',   0.60, ...
    'beta',    0.10, ...
    'P_move',  0.15, ...
    'A_i',     0.20, ...
    'T_cell',  4, ...
    'delta',   1e-4);

P.provenance = struct( ...
    'alpha',   'Framework: Anderson 2005 (division as a rate). Numeric value TBD.', ...
    'beta',    'Framework: Anderson 2005 contact-inhibition concept. Numeric value TBD.', ...
    'P_move',  'Framework: Anderson 2005 / Drasdo & Hohme 2005 migration. Value TBD.', ...
    'A_i',     'Anderson 2005 adhesion threshold. Value TBD.', ...
    'T_cell',  'Fixed in Part 2 to remove alpha/T_cell non-identifiability. TBD (order 1 day in vivo).', ...
    'delta',   'TBD (apoptosis rate).', ...
    'L',       'TBD: diffusion length, order 100-200 um in tissue; swept as L in arm B.', ...
    'C0',      'Normalised far-field nutrient; dimensionless by construction.', ...
    'C_min',   'TBD: hypoxic threshold.', ...
    'C_q',     'TBD: quiescence threshold.');
end
